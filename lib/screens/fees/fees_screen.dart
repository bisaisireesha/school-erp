                                  if (formattedAmt.length > 3) {
                                    formattedAmt = '${formattedAmt.substring(0, formattedAmt.length - 3)},${formattedAmt.substring(formattedAmt.length - 3)}';
                                  }
                                  _mockData!['outstandingBalance']['amount'] = formattedAmt;
                                });

                                setModalState(() {
                                  isProcessing = false;
                                  isSuccess = true;
                                });
                              }
                            });
                          },
                          style: ElevatedButton.styleFrom(
                            backgroundColor: const Color(0xFF6C4CF1),
                            foregroundColor: Colors.white,
                            elevation: 0,
                            padding: const EdgeInsets.symmetric(vertical: 16),
                            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(16)),
                          ),
                          child: const Text('Pay Now', style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold)),
                        ),
                      ),
                    ],
                  ],
                ),
              );
            },
          ),
        );
      },
    );
  }



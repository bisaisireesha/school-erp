  Future<void> _simulateDownload(String itemName) async {
    // Show downloading dialog
    showDialog(
      context: context,
      barrierDismissible: false,
      builder: (context) {
        return Dialog(
          backgroundColor: Colors.white,
          shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(20)),
          child: Padding(
            padding: const EdgeInsets.all(24.0),
            child: Row(
              mainAxisSize: MainAxisSize.min,
              children: [
                const SizedBox(
                  width: 24,
                  height: 24,
                  child: CircularProgressIndicator(color: Color(0xFF6C4CF1), strokeWidth: 3),
                ),
                const SizedBox(width: 20),
                Expanded(child: Text('Generating $itemName...', style: const TextStyle(fontSize: 16, fontWeight: FontWeight.bold, color: Color(0xFF1E1E2D)))),
              ],
            ),
          ),
        );
      },
    );

    try {
      // 1. Generate PDF
      final pdf = pw.Document();
      pdf.addPage(
        pw.Page(
          pageFormat: PdfPageFormat.a4,
          build: (pw.Context context) {
            return pw.Center(
              child: pw.Column(
                mainAxisAlignment: pw.MainAxisAlignment.center,
                children: [
                  pw.Text('Receipt / Invoice', style: pw.TextStyle(fontSize: 32, fontWeight: pw.FontWeight.bold)),
                  pw.SizedBox(height: 20),
                  pw.Text(itemName, style: const pw.TextStyle(fontSize: 24)),
                  pw.SizedBox(height: 40),
                  pw.Text('Generated by Parent App on ${DateTime.now().toString().split('.')[0]}', style: const pw.TextStyle(fontSize: 14)),
                ],
              ),
            );
          },
        ),
      );

      // Fake delay for realistic feel
      await Future.delayed(const Duration(seconds: 1));

      // 2. Save file
      Directory? dir;
      if (Platform.isAndroid) {
        // Use external storage for Android so it goes to real Downloads or Documents
        dir = await getExternalStorageDirectory();
      } else {
        dir = await getApplicationDocumentsDirectory();
      }
      
      if (dir == null) throw Exception("Could not find directory to save file");
      
      final String safeName = itemName.replaceAll(RegExp(r'[^a-zA-Z0-9]'), '_');
      final String filePath = '${dir.path}/$safeName.pdf';
      final file = File(filePath);
      await file.writeAsBytes(await pdf.save());

      // Close dialog
      if (mounted) Navigator.pop(context);
      
      // Show success snackbar with Open button
      if (mounted) {
        ScaffoldMessenger.of(context).clearSnackBars();
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Row(
              children: [
                const Icon(Icons.check_circle_outline, color: Colors.white),
                const SizedBox(width: 12),
                const Expanded(child: Text('Saved as PDF successfully!', style: TextStyle(fontWeight: FontWeight.bold))),
              ],
            ),
            action: SnackBarAction(
              label: 'OPEN',
              textColor: Colors.white,
              onPressed: () {
                OpenFile.open(filePath);
              },
            ),
            backgroundColor: const Color(0xFF4CAF50),
            behavior: SnackBarBehavior.floating,
            shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
            margin: const EdgeInsets.all(20),
            duration: const Duration(seconds: 2), // Reduced duration
          ),
        );
      }
    } catch (e) {
      if (mounted) {
        Navigator.pop(context); // close dialog
        ScaffoldMessenger.of(context).clearSnackBars();
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(
            content: Text('Failed to download: $e'),
            backgroundColor: Colors.red,
            duration: const Duration(seconds: 2), // Reduced duration
          )
        );
      }
    }
  }

